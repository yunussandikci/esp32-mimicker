enum Layout : uint8_t {
  LAYOUT_US=0, LAYOUT_UK, LAYOUT_DE, LAYOUT_FR, LAYOUT_ES,
  LAYOUT_IT, LAYOUT_PT, LAYOUT_TR_Q, LAYOUT_TR_F, LAYOUT_COUNT
};
constexpr uint8_t MOD_SHIFT = 0x01;
constexpr uint8_t MOD_ALTGR = 0x02;

struct Entry { uint32_t cp; uint8_t hid; uint8_t mods; };

inline const char* name(Layout l) {
  static const char* N[] = {"US","UK","DE","FR","ES","IT","PT","TR_Q","TR_F"};
  return l < LAYOUT_COUNT ? N[l] : "US";
}

inline Layout from_name(const String& s) {
  for (uint8_t i = 0; i < LAYOUT_COUNT; i++)
    if (s == name((Layout)i)) return (Layout)i;
  return LAYOUT_US;
}

