#define SZ(a) (sizeof(a)/sizeof(Entry))

struct LayoutDef {
  const uint8_t* letters;     // 26-byte a..z position LUT, or nullptr
  const Entry*   table;       // overrides + non-letter chars
  uint16_t       count;
};

inline constexpr LayoutDef LAYOUTS[LAYOUT_COUNT] = {
  /* US   */ { nullptr,        nullptr,  0 },
  /* UK   */ { QWERTY,         UK_TBL,   SZ(UK_TBL)   },
  /* DE   */ { QWERTZ,         DE_TBL,   SZ(DE_TBL)   },
  /* FR   */ { AZERTY,         FR_TBL,   SZ(FR_TBL)   },
  /* ES   */ { QWERTY,         ES_TBL,   SZ(ES_TBL)   },
  /* IT   */ { QWERTY,         IT_TBL,   SZ(IT_TBL)   },
  /* PT   */ { QWERTY,         PT_TBL,   SZ(PT_TBL)   },
  /* TR_Q */ { QWERTY,         TR_Q_TBL, SZ(TR_Q_TBL) },
  /* TR_F */ { TR_F_LETTERS,   TR_F_TBL, SZ(TR_F_TBL) },
};

inline bool find(Layout l, uint32_t cp, uint8_t* out_hid, uint8_t* out_mods) {
  const LayoutDef& def = LAYOUTS[l];
  // 1. Table override (catches non-ASCII, punctuation, and TR_Q's i/I)
  for (uint16_t i = 0; i < def.count; i++) {
    if (def.table[i].cp == cp) {
      *out_hid = def.table[i].hid;
      *out_mods = def.table[i].mods;
      return true;
    }
  }
  // 2. a..z / A..Z via LUT
  if (def.letters) {
    if (cp >= 'a' && cp <= 'z') { *out_hid = def.letters[cp - 'a']; *out_mods = 0;         return true; }
    if (cp >= 'A' && cp <= 'Z') { *out_hid = def.letters[cp - 'A']; *out_mods = MOD_SHIFT; return true; }
  }
  return false;
}

inline size_t utf8_decode(const char* s, size_t len, uint32_t* out_cp) {
  if (len == 0) return 0;
  uint8_t b0 = (uint8_t)s[0];
  if (b0 < 0x80) { *out_cp = b0; return 1; }
  if ((b0 & 0xE0) == 0xC0 && len >= 2) {
    *out_cp = ((b0 & 0x1F) << 6) | ((uint8_t)s[1] & 0x3F); return 2;
  }
  if ((b0 & 0xF0) == 0xE0 && len >= 3) {
    *out_cp = ((b0 & 0x0F) << 12) | (((uint8_t)s[1] & 0x3F) << 6) | ((uint8_t)s[2] & 0x3F); return 3;
  }
  if ((b0 & 0xF8) == 0xF0 && len >= 4) {
    *out_cp = ((b0 & 0x07) << 18) | (((uint8_t)s[1] & 0x3F) << 12) | (((uint8_t)s[2] & 0x3F) << 6) | ((uint8_t)s[3] & 0x3F); return 4;
  }
  return 0;
}

